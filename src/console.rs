//! Декодирование вывода консольных программ Windows.
//!
//! ЗАЧЕМ ЭТО НУЖНО. Консольные утилиты Windows (`tasklist`, `netstat`,
//! `net user`, `systeminfo`) выводят текст в КОДОВОЙ СТРАНИЦЕ КОНСОЛИ,
//! а не в UTF-8. На русской Windows это обычно CP866, на части систем —
//! CP1251. Если читать такой вывод как UTF-8, русские буквы превратятся
//! в мусор («╧ЁышЄ√»), и сообщения реагирования станут нечитаемыми —
//! а оператор по ним принимает решения.
//!
//! ПОЧЕМУ КОДОВАЯ СТРАНИЦА ОПРЕДЕЛЯЕТСЯ В РАНТАЙМЕ. Хардкодить CP866
//! нельзя: на английской Windows это CP437, а в многоязычных системах
//! кодовая страница OEM может быть изменена. Windows предоставляет
//! функцию `GetOEMCP`, и правильный источник истины — она.
//!
//! ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ТЕСТАМИ. Само определение кодовой страницы
//! требует Windows, поэтому оно вынесено в `sysops.rs`. Здесь только
//! ПРЕОБРАЗОВАНИЕ байтов в строку по известному номеру — чистая функция,
//! проверяемая на любой платформе. Именно она содержит ошибкоопасную
//! логику: неверное кодирование портит текст молча, не выдавая ошибки.

/// Соответствие номера кодовой страницы Windows кодировке.
///
/// Возвращает `None` для неизвестной страницы: в этом случае лучше
/// показать вывод как есть, чем подставить неправильную кодировку
/// и получить искажённый текст.
pub fn encoding_for_code_page(code_page: u32) -> Option<&'static encoding_rs::Encoding> {
    match code_page {
        // Русская OEM (консоль) и ANSI.
        866 => Some(encoding_rs::IBM866),
        1251 => Some(encoding_rs::WINDOWS_1251),

        // Западноевропейская ANSI: типична для английской Windows.
        //
        // ОГРАНИЧЕНИЕ, О КОТОРОМ НУЖНО ЗНАТЬ. Однобайтовых кодовых
        // страниц OEM для западноевропейских языков (CP437, CP850, CP852)
        // в библиотеке encoding_rs НЕТ: она поддерживает только IBM866
        // из OEM-набора. Для этих страниц возвращается None, и текст
        // читается как CP866 (см. FALLBACK_CODE_PAGE).
        //
        // Практическое следствие: на АНГЛИЙСКОЙ Windows русских букв
        // в выводе утилит и не будет (интерфейс английский), а латиница
        // и цифры в CP866 и CP437 совпадают, поэтому сообщения остаются
        // читаемыми. Искажаются только специфические символы псевдографики,
        // которые в сообщениях оператору не используются.
        1252 => Some(encoding_rs::WINDOWS_1252),

        // UTF-8: сюда попадают системы с включённой поддержкой UTF-8
        // (в Windows 10 это параметр «Бета-версия: использование Юникода
        // UTF-8 для поддержки языковых стандартов по всему миру»).
        65001 => Some(encoding_rs::UTF_8),

        _ => None,
    }
}

/// Кодировка, используемая по умолчанию, если определить её не удалось.
///
/// CP866 выбран потому, что целевые узлы — русскоязычные системы
/// (Windows 10), а эта кодировка является для них стандартной для консоли.
/// Из OEM-наборов библиотека поддерживает только её.
///
/// ВАЖНО: запасная кодировка применяется и тогда, когда номер страницы
/// известен, но соответствующей кодировки нет в библиотеке (CP437, CP850).
pub const FALLBACK_CODE_PAGE: u32 = 866;

/// Преобразует вывод консольной программы в строку по номеру страницы.
///
/// ПОЧЕМУ ЧЕРЕЗ ПОТЕРИ, А НЕ ЧЕРЕЗ ОШИБКУ. Отдельные байты вывода могут
/// не иметь представления в целевой кодировке (например, если программа
/// смешала кодировки). Выводить из-за этого пустую строку недопустимо:
/// оператору нужен хотя бы частичный текст — в нём может быть причина
/// отказа. Поэтому непереводимые байты заменяются, а остальное читается.
pub fn decode_console_output(bytes: &[u8], code_page: u32) -> String {
    let encoding = encoding_for_code_page(code_page);

    let decoded = match encoding {
        Some(encoding) => encoding.decode(bytes).0,
        None => {
            // Кодировка неизвестна. Пробуем CP866 как наиболее вероятную
            // для целевых узлов; если и она не подходит, остаётся
            // lossy-чтение UTF-8, которое не паникует.
            match encoding_for_code_page(FALLBACK_CODE_PAGE) {
                Some(fallback) => fallback.decode(bytes).0,
                None => String::from_utf8_lossy(bytes),
            }
        }
    };

    normalize_console_text(&decoded)
}

/// Приводит вывод консольной программы к аккуратному виду.
///
/// Убирает завершающие пробелы и пустые строки, а также символ возврата
/// каретки: некоторые утилиты Windows завершают строки парой `\r\n`,
/// и без очистки в сообщении оператору остались бы лишние символы.
pub fn normalize_console_text(text: &str) -> String {
    text.replace("\r\n", "\n")
        .replace('\r', "\n")
        .lines()
        .map(|line| line.trim_end())
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn русская_кодировка_консоли_распознаётся() {
        assert_eq!(
            encoding_for_code_page(866).map(|e| e.name()),
            Some("IBM866")
        );
        assert_eq!(
            encoding_for_code_page(1251).map(|e| e.name()),
            Some("windows-1251")
        );
    }

    #[test]
    fn западноевропейская_ansi_распознаётся() {
        assert!(encoding_for_code_page(1252).is_some());
    }

    #[test]
    fn латиница_читается_одинаково_в_любой_поддерживаемой_кодировке() {
        // Английская Windows использует OEM-страницы (CP437/CP850),
        // которых нет в encoding_rs. Проверяем главное: латинский текст
        // и цифры в них совпадают с CP866, поэтому сообщения об ошибках
        // остаются читаемыми, даже если кодировка определена неточно.
        let text = b"ERROR: The process \"cmd.exe\" not found";
        assert_eq!(decode_console_output(text, 866), decode_console_output(text, 1252));
    }

    #[test]
    fn западные_oem_страницы_честно_сообщают_об_отсутствии() {
        // Эти кодовые страницы в библиотеке не поддерживаются.
        // Возврат None — это сигнал применить запасную кодировку,
        // а не выдать искажённый текст молча.
        assert!(encoding_for_code_page(437).is_none());
        assert!(encoding_for_code_page(850).is_none());
    }

    #[test]
    fn utf8_распознаётся() {
        // Системы с включённой поддержкой UTF-8 отдают вывод в UTF-8.
        let text = decode_console_output("привет".as_bytes(), 65001);
        assert_eq!(text, "привет");
    }

    #[test]
    fn русский_текст_в_cp866_читается_верно() {
        // слово «ошибка» в CP866: байты сверены с таблицей кодировки,
        // а не подобраны на глаз
        let bytes = [0xAE, 0xE8, 0xA8, 0xA1, 0xAA, 0xA0];
        assert_eq!(decode_console_output(&bytes, 866), "ошибка");
    }

    #[test]
    fn русский_текст_в_cp1251_читается_верно() {
        // то же слово в CP1251 — БАЙТЫ ДРУГИЕ, поэтому кодировку нельзя
        // угадывать: перепутанная кодировка даст мусор без всякой ошибки.
        let bytes = [0xEE, 0xF8, 0xE8, 0xE1, 0xEA, 0xE0];
        assert_eq!(decode_console_output(&bytes, 1251), "ошибка");
    }

    #[test]
    fn неверная_кодировка_даёт_не_тот_текст() {
        // Проверяем, что разница между кодировками действительно есть:
        // это обоснование того, почему кодировка определяется в рантайме.
        let cp1251_bytes = [0xEE, 0xF8, 0xE8, 0xE1, 0xEA, 0xE0];
        let as_cp866 = decode_console_output(&cp1251_bytes, 866);
        let as_cp1251 = decode_console_output(&cp1251_bytes, 1251);

        assert_ne!(as_cp866, as_cp1251);
        assert_eq!(as_cp1251, "ошибка");
    }

    #[test]
    fn неизвестная_кодировка_не_паникует_и_что_то_возвращает() {
        let text = decode_console_output(b"plain ascii text", 99999);
        assert_eq!(text, "plain ascii text");
    }

    #[test]
    fn пустой_вывод_даёт_пустую_строку() {
        assert_eq!(decode_console_output(&[], 866), "");
    }

    #[test]
    fn завершающие_пробелы_и_переводы_строк_убираются() {
        let text = normalize_console_text("строка один   \r\nстрока два  \r\n\r\n");
        assert_eq!(text, "строка один\nстрока два");
    }

    #[test]
    fn вывод_без_завершающей_строки_не_портится() {
        assert_eq!(normalize_console_text("одна строка"), "одна строка");
    }

    #[test]
    fn ascii_вывод_одинаков_в_любой_кодировке() {
        // Вывод латинских утилит от кодировки не зависит: это
        // подтверждает, что декодирование не портит обычный текст.
        let bytes = b"PID 1234 not found";
        assert_eq!(decode_console_output(bytes, 866), "PID 1234 not found");
        assert_eq!(decode_console_output(bytes, 1251), "PID 1234 not found");
        assert_eq!(decode_console_output(bytes, 437), "PID 1234 not found");
    }
}
